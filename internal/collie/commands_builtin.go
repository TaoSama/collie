// Each CLI's own commands, as its "/" menu lists them. Claude Code's come from
// its command reference (code.claude.com/docs/en/commands, 2026-11), without
// removed ones, aliases and those hidden until typed in full; Codex's from
// codex-rs/tui/src/slash_command.rs at rust-v0.172.0, without the debug,
// alias and platform-only ones the popup hides; Antigravity CLI's from its
// reference (antigravity.google/docs/cli/reference). A newer or older CLI on
// another computer may have a few more or fewer.

